"""Contre-lecture de la grille brouillon 2 : vérifications complémentaires sur la moitié développement.
Usage : python verifs_complementaires_dev_v1.py W   (W contient copies-dev/). Affiche des extraits à l écran ; n écrit dans W/verifs2.json que des décomptes."""
RES={}
import json, re, sys, collections, statistics, numpy as np
W=sys.argv[1]
man=json.load(open('/home/user/controle-ia-travail/docs/notes/billets-v1/manifeste-corpus-v2.json'))
dev={b['identifiant']:b for b in man['billets'] if b['moitie']=='developpement'}
table=json.load(open(f'{W}/copies-dev/cles/table-de-correspondance.json'))['neutre_vers_site']
inv={v:k for k,v in table.items()}
BORNE="⟦FIN DE L'EN-TÊTE — 250 MOTS⟧"
T={i:open(f'{W}/copies-dev/codeurs/billets/{inv[i]}.md',encoding='utf-8').read() for i in dev}
# 1. exception de prévalence haute sous indépendance totale des codeurs
rng=np.random.default_rng(np.random.SeedSequence(271828182845904523536028747135266249775).spawn(2)[1])
for prev in (0.92,0.95,0.97):
    A=rng.random((50000,62))<prev; B=rng.random((50000,62))<prev
    ok=np.ones(50000,bool)
    for n in (62,44):
        po=(A[:,:n]==B[:,:n]).mean(1); pa=A[:,:n].mean(1); pb=B[:,:n].mean(1); pr=(pa+pb)/2
        pe=pa*pb+(1-pa)*(1-pb); k=np.where(pe<1,(po-pe)/np.where(pe<1,1-pe,1),-1)
        ok&=np.where(pr>0.90,po>=0.90,np.where(pr<0.10,False,k>=0.60))
    print(f"codeurs indépendants (kappa vrai 0), prévalence {prev}: déclaré fiable {ok.mean():.3f}")
    RES.setdefault("exception_prevalence_haute_codeurs_independants",{})[str(prev)]=float(ok.mean())
# 2. images : part avec texte de remplacement ; part suivie d'une ligne de légende courte
n_img=n_alt=n_leg=0
for i,t in T.items():
    lines=t.split('\n')
    for j,l in enumerate(lines):
        for m in re.finditer(r"\[IMAGE \d+( : [^\]]*)?\]",l):
            n_img+=1; n_alt+=bool(m.group(1))
            # légende : prochaine ligne non vide, courte (< 60 mots), qui n'est pas une image ni un intertitre
            k=j+1
            while k<len(lines) and not lines[k].strip(): k+=1
            if k<len(lines):
                nx=lines[k].strip()
                if l.strip()==m.group(0) and not nx.startswith('[IMAGE') and not re.match(r"^(#|=+$|-+$|\*   |\d+\.  )",nx) and re.match(r"^(\*{0,3})(Figure|Fig\.|Plot|Diagram|Table|Caption)",nx,re.I):
                    n_leg+=1
RES["images"]={"total":n_img,"avec_texte_de_remplacement":n_alt,"suivies_d_une_legende_Figure_Plot_Diagram_Table":n_leg}
print('images',n_img,'avec texte de remplacement',n_alt,'suivies d une légende commençant par Figure/Plot/Diagram/Table',n_leg)
sans=[i for i,t in T.items() if re.search(r"\[IMAGE \d+",t) and not re.search(r"\[IMAGE \d+ : ",t)]
RES["billets_avec_images_sans_aucun_texte_de_remplacement"]=[len(sans),sum(1 for t in T.values() if re.search(r"\[IMAGE \d+",t))]
print('billets avec images mais aucun texte de remplacement:',len(sans),'sur',sum(1 for t in T.values() if re.search(r"\[IMAGE \d+",t)))
# 3. position du premier résumé étiqueté (en jetons du corps)
lab=re.compile(r"(?im)^\W{0,6}(TL\W?DR|Summary|Executive summary|Abstract|Overview|Key results|High-level takeaways|One-sentence summary|Bottom line|Main takeaways|Key takeaways|Key findings)\b")
pos=[]
for i,t in T.items():
    corps=t.split('\n\n',1)[1].replace(BORNE,' ')
    m=lab.search(corps)
    if m:
        pos.append((len(re.findall(r"\S+",corps[:m.start()])),i,dev[i]['classe'],m.group(1)))
pos.sort()
RES["etiquette_de_resume"]={"billets_avec_etiquette":len(pos),"avant_le_250e_jeton":sum(p[0]<250 for p in pos),"entre_250_et_500":[[p[0],p[1],p[2]] for p in pos if 250<=p[0]<500]}
print('billets avec une étiquette de résumé quelque part:',len(pos))
print('  dont étiquette avant le 250e jeton:',sum(p[0]<250 for p in pos),'; entre 250 et 500:',[(p[0],p[1],p[2],p[3]) for p in pos if 250<=p[0]<500])
# 4. déclarations d'usage d'un modèle dans l'écriture (repérage large, à lire à la main)
rx=re.compile(r"[^.\n]*\b(Claude|ChatGPT|GPT-?\d\w*|Gemini|Opus|LLM|AI)\b[^.\n]{0,80}\b(paraphras\w*|proofread\w*|copy-?edit\w*|formatting help|writing|wrote|written|drafted|drafting|edited|editing help|rewrit\w*|generated by the help)\b[^.\n]*",re.I)
rx2=re.compile(r"[^.\n]*\b(paraphras\w*|proofread\w*|copy-?edit\w*|formatting help|help(ed)? (me )?(write|draft|edit)|written (with|by)|drafted (with|by)|wrote (this|the) (post|draft|section|summary))\b[^.\n]{0,80}\b(Claude|ChatGPT|GPT-?\d\w*|Gemini|Opus|LLM|AI)\b[^.\n]*",re.I)
for i,t in T.items():
    for m in list(rx.finditer(t))+list(rx2.finditer(t)):
        s=' '.join(m.group(0).split())
        if len(s)<400: print('  IA?',i,dev[i]['classe'],'|',s[:260])
# 5. hôtes des liens par classe (laboratoires)
hosts=collections.defaultdict(lambda: collections.Counter())
for i,t in T.items():
    for h in set(re.findall(r"\[lien : ([^\]]+)\]",t)): hosts[h][dev[i]['classe']]+=1
RES["hotes_par_classe"]={h:dict(hosts.get(h,{})) for h in ['matsprogram.org','deepmind.google','apolloresearch.ai','transformer-circuits.pub','alignmentforum.org','github.com']}
for h in ['anthropic.com','transformer-circuits.pub','deepmind.google','openai.com','apolloresearch.ai','redwoodresearch.org','alignmentforum.org','lesswrong.com','arxiv.org','github.com','matsprogram.org','neuronpedia.org']:
    print('  hôte',h,dict(hosts.get(h,{})))
# 6. autres fuites : mentions du site, de sa revue, de discussions passées
rx3=re.compile(r"[^.\n]*\b(many people (said|asked|pointed)|commenters?|in the comments|as (several|many) (people|commenters)|this post (was|has been|got)|crosspost\w*|linkpost|accepted (to|at)|spotlight|oral at|NeurIPS|ICLR|ICML|Nature|press coverage|went viral|first (interpretability |research |ML )?(project|post)|new to (the field|alignment|interpretability)|weeks into)\b[^.\n]*",re.I)
c=collections.Counter(); ex=[]
for i,t in T.items():
    ms=[' '.join(m.group(0).split())[:170] for m in rx3.finditer(t)]
    if ms: c[dev[i]['classe']]+=1; ex.append((i,dev[i]['classe'],ms[0]))
print('billets avec au moins une mention de ce genre, par classe:',dict(c),'sur bien notés 36, appariés 22')
for e in ex[:14]: print('   ',e)
json.dump(RES,open(f'{W}/verifs2.json','w'),ensure_ascii=False,indent=1)
