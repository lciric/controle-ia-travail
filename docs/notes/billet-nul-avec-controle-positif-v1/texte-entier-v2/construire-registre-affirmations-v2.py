def sha(p: pathlib.Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main() -> None:
    reg = {"sources": {}, "pdf": {}, "entrees": []}
    lignes = {}
    for k, rel in SOURCES.items():
        p = DEPOT / rel
        h = sha(p)
        comp = p.parent / (p.name + ".sha256")
        comp_h = comp.read_text(encoding="utf-8").split()[0] if comp.exists() else None
        if comp_h and comp_h != h:
            sys.exit(f"source {k}: sha256 {h} != compagnon {comp_h}")
        reg["sources"][k] = {"chemin": rel, "sha256": h, "compagnon_sha256": comp_h}
        lignes[k] = p.read_text(encoding="utf-8").splitlines()

    for k, info in PDF.items():
        local_p = DEPOT / info["chemin_local"]
        if local_p.exists() and sha(local_p) != info["sha256"]:
            sys.exit(f"PDF local {k}: sha256 != attendu")
        reg["pdf"][k] = dict(info)

    non_uniques = []
    for i, (sec, n, ctx, qual, est_page, src, val, motif, note) in enumerate(E_, 1):
        entry = {
            "n": i,
            "section": sec,
            "nombre": n,
            "contexte_billet": ctx,
            "qualificatif": qual,
            "est_page": est_page,
            "source": src,
            "valeur_source": val,
            "motif": motif,
            "note": note,
        }
        if not src.startswith("PDF:"):
            trouve = [j + 1 for j, l in enumerate(lignes[src]) if motif in l]
            if not trouve:
                sys.exit(f"entrée {i} ({n}, section {sec}) : motif absent de {src}: {motif!r}")
            entry["ligne"] = trouve[0]
            entry["lignes_portant_le_motif"] = len(trouve)
            if len(trouve) != 1:
                non_uniques.append((i, n, src, trouve))
        reg["entrees"].append(entry)

    if non_uniques:
        sys.exit(f"motifs non uniques détectés : {non_uniques}")

    sortie = ICI / "registre-affirmations-v2.json"
    sortie.write_text(json.dumps(reg, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"registre-affirmations-v2.json écrit : {len(reg['entrees'])} entrées, toutes uniques à 1 ligne.")


if __name__ == "__main__":
    main()
